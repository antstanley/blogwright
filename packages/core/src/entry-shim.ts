/**
 * The generated SSR entry shim. Lambda passes the listen address in
 * `AWS_LAMBDA_HTTP_ENDPOINT`; most framework servers read their own host and
 * port variables instead. With `ssr.shim` set, the CLI generates this file, the
 * build agent adds it to the package beside `ssr.entryPoint`, and the revision
 * starts it in place of the entry, so the site's build no longer has to emit one.
 */

import { SSR_SHIM_FILE, type SsrConfig } from './config.js';

/** A file the build agent adds to the package, at a path inside the archive. */
export interface EntryShim {
  path: string;
  source: string;
}

/** The shim for an `ssr` block, or undefined when the entry listens by itself. */
export function entryShim(ssr: SsrConfig): EntryShim | undefined {
  if (!ssr.shim) return undefined;
  const slash = ssr.entryPoint.lastIndexOf('/');
  const entryDir = ssr.entryPoint.slice(0, slash + 1);
  const entryFile = ssr.entryPoint.slice(slash + 1);
  const lines = [
    '// Generated by blogwright from config.ssr.shim. Lambda passes the listen',
    '// address in AWS_LAMBDA_HTTP_ENDPOINT; this maps it onto the variables the',
    '// server reads, then starts the server.',
    'const endpoint = process.env.AWS_LAMBDA_HTTP_ENDPOINT;',
    "if (!endpoint) throw new Error('AWS_LAMBDA_HTTP_ENDPOINT is not set');",
    "const colon = endpoint.lastIndexOf(':');",
    ...(ssr.shim.host
      ? [
          "const host = endpoint.slice(0, colon).replace(/^\\[(.*)\\]$/, '$1');",
          `process.env[${JSON.stringify(ssr.shim.host)}] = host;`,
        ]
      : []),
    `process.env[${JSON.stringify(ssr.shim.port)}] = endpoint.slice(colon + 1);`,
    `await import(${JSON.stringify(`./${entryFile}`)});`,
  ];
  return { path: `${entryDir}${SSR_SHIM_FILE}`, source: `${lines.join('\n')}\n` };
}

/** The file the revision starts: the shim when one is generated, else the entry itself. */
export function runtimeEntryPoint(ssr: SsrConfig): string {
  return entryShim(ssr)?.path ?? ssr.entryPoint;
}
