/**
 * The approved budget: `package-sizes.json` at the repository root records
 * each published package's maximum install size. A measurement above its
 * maximum fails; at or below passes. Raising a maximum means rewriting the
 * file with `pnpm size:update` and committing it, so the increase is a
 * reviewed line in the pull request rather than something CI lets through.
 */

import type { PackageMeasurement } from './measure.js';

export const BASELINE_FILE = 'package-sizes.json';

/** Stable, locale-independent ordering for package names. */
const NAME_ORDER = new Intl.Collator('en');

const BASELINE_NOTE =
  'Maximum install size in bytes of each published package (own files plus production dependencies, for the target platform). Generated by `pnpm size:update`; an increase is approved by committing this file.';

export interface Baseline {
  /** The platform the maximums were measured for, e.g. `linux-x64-glibc`. */
  readonly target: string;
  /** Package name to maximum install size in bytes. */
  readonly maximums: ReadonlyMap<string, number>;
}

/** Parse and validate the baseline file, naming the file and field on any error. */
export function parseBaseline(text: string, source: string): Baseline {
  let raw: unknown;
  try {
    raw = JSON.parse(text);
  } catch (err) {
    throw new Error(`${source} is not valid JSON: ${(err as Error).message}`, { cause: err });
  }
  if (!isRecord(raw)) throw new Error(`${source} must contain a JSON object`);
  if (typeof raw['target'] !== 'string' || raw['target'] === '') {
    throw new Error(`${source}: "target" must be a platform string such as "linux-x64-glibc"`);
  }
  const packages = raw['packages'];
  if (!isRecord(packages))
    throw new Error(`${source}: "packages" must be an object of package name to bytes`);

  const maximums = new Map<string, number>();
  for (const [name, bytes] of Object.entries(packages)) {
    if (typeof bytes !== 'number' || !Number.isSafeInteger(bytes) || bytes <= 0) {
      throw new Error(
        `${source}: packages.${name} must be a positive whole number of bytes, got ${JSON.stringify(bytes)}`,
      );
    }
    maximums.set(name, bytes);
  }
  return { target: raw['target'], maximums };
}

/** The baseline file text for these measurements: keys sorted, trailing newline. */
export function serializeBaseline(
  measurements: readonly PackageMeasurement[],
  target: string,
): string {
  const packages = Object.fromEntries(
    [...measurements]
      .sort((a, b) => NAME_ORDER.compare(a.name, b.name))
      .map((measurement) => [measurement.name, measurement.installSize]),
  );
  return `${JSON.stringify({ '//': BASELINE_NOTE, target, packages }, null, 2)}\n`;
}

type BudgetStatus = 'within' | 'over' | 'unbudgeted';

export interface BudgetRow {
  readonly measurement: PackageMeasurement;
  /** The approved maximum, absent for a package the baseline does not list. */
  readonly maximum: number | undefined;
  readonly status: BudgetStatus;
}

export interface BudgetResult {
  readonly rows: readonly BudgetRow[];
  /** Baseline entries for packages that are no longer published. */
  readonly stale: readonly string[];
}

/**
 * Compare measurements against the baseline. Raises when the baseline was
 * measured for a different platform, since its numbers would not be comparable.
 */
export function compareToBaseline(
  measurements: readonly PackageMeasurement[],
  baseline: Baseline,
  target: string,
): BudgetResult {
  if (baseline.target !== target) {
    throw new Error(
      `${BASELINE_FILE} was measured for ${baseline.target} but sizes are now measured for ${target} - run pnpm size:update to re-measure`,
    );
  }
  const rows = measurements.map((measurement): BudgetRow => {
    const maximum = baseline.maximums.get(measurement.name);
    if (maximum === undefined) return { measurement, maximum, status: 'unbudgeted' };
    return { measurement, maximum, status: measurement.installSize > maximum ? 'over' : 'within' };
  });
  const measured = new Set(measurements.map((measurement) => measurement.name));
  const stale = [...baseline.maximums.keys()].filter((name) => !measured.has(name)).sort();
  return { rows, stale };
}

/** True when every package is within its maximum and the baseline lists exactly the published packages. */
export function budgetPasses(result: BudgetResult): boolean {
  return result.stale.length === 0 && result.rows.every((row) => row.status === 'within');
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}
